//! Default listener ports. Each listener kind has a disjoint 1000-port block,
//! Console web and Access start at 6135, 7135, 8135 and 9135. Management and RPC
//! listeners of the same server are 1000 ports apart. Instances use stride 1:
//! host-network nodes use base + node offset (0, 1, 2 for three nodes).
//! The allocator checks claims and bind availability; configured endpoints
//! remain authoritative and are not migrated by changing these defaults.
//!
//! Paxos-KV: 10135 management / 11135 RPC.
//! `DiskDB`: 13135 management / 14135 RPC.
//! `ChunkDB`: 16135 management / 17135 RPC.
//! `DiskIO`: 18135 RPC. Console web: 6135 HTTP.
//! Chunk-KV: 20135 management / 21135 RPC.
//! Access: 7135 S3 / 8135 Iceberg / 9135 Dataset / 25135 health.
//! Monitor: 26135 HTTP. SSH: 2222 (no instance block).
//! Rust callers import these constants. Non-Rust defaults are generated by
//! `pixi run python tools/ports/generate.py`; `--check` detects stale outputs.

/// crowdb-paxos-kv-server HTTP management API — base port. Also the famous
/// group-0 bootstrap discovery port.
pub const PAXOS_KV_SERVER_MGMT_BASE: u16 = 10135;

/// crowdb-paxos-kv-server main `PxKvStore` listener — base port (port pool).
/// Hosts both consensus and client crowdb-rpc handlers on the same
/// listener (RPC port collapse — no separate consensus/client ports).
pub const PAXOS_KV_SERVER_RPC_BASE: u16 = 11135;

/// crowdb-diskdb HTTP management API — base port.
pub const DISKDB_HTTP_BASE: u16 = 13135;

/// crowdb-diskdb crowdb-rpc listener — base port.
pub const DISKDB_RPC_BASE: u16 = 14135;

/// crowdb-chunkdb HTTP management API — base port.
pub const CHUNKDB_HTTP_BASE: u16 = 16135;

/// crowdb-chunkdb crowdb-rpc listener — base port.
pub const CHUNKDB_RPC_BASE: u16 = 17135;

/// crowdb-diskio crowdb-rpc listener — base port.
pub const DISKIO_RPC_BASE: u16 = 18135;

/// crowdb-web HTTP service — base port.
pub const WEB_BASE: u16 = 6135;

/// crowdb-chunk-kv-server HTTP management API — base port.
pub const CHUNK_KV_HTTP_BASE: u16 = 20135;

/// crowdb-chunk-kv-server crowdb-rpc listener — base port.
pub const CHUNK_KV_RPC_BASE: u16 = 21135;

/// crowdb-access-server S3 HTTP service — base port.
pub const ACCESS_SERVER_HTTP_BASE: u16 = 7135;

/// crowdb-access-server Iceberg HTTP service — base port.
pub const ACCESS_SERVER_ICEBERG_HTTP_BASE: u16 = 8135;

/// crowdb-access-server Dataset HTTP service — base port.
pub const ACCESS_SERVER_DATASET_HTTP_BASE: u16 = 9135;

/// Independent Access health listener.
pub const ACCESS_SERVER_HEALTH_HTTP_BASE: u16 = 25135;

/// Node monitor discovery and management HTTP listener.
pub const MONITOR_HTTP_BASE: u16 = 26135;

/// Container SSH listener; outside service instance allocation.
pub const SSH_PORT: u16 = 2222;

/// Standard SSH endpoint for externally managed hosts.
pub const HOST_SSH_PORT: u16 = 22;

/// CROWDB service type for default port allocation.
///
/// Use [`ServicePort::port`] to compute the listen port for the
/// `instance`-th instance of a service type on a given node (0-based).
/// The base constants (e.g. [`PAXOS_KV_SERVER_MGMT_BASE`]) are re-exported
/// for contexts that need a plain `const` value (clap `default_value_t`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ServicePort {
    /// crowdb-paxos-kv-server HTTP management API.
    PaxosKvServerMgmt,
    /// crowdb-paxos-kv-server main `PxKvStore` listener (port pool; hosts
    /// both consensus and client crowdb-rpc).
    PaxosKvServerRpc,
    /// crowdb-diskdb HTTP management API.
    DiskdbHttp,
    /// crowdb-diskdb crowdb-rpc listener.
    DiskdbRpc,
    /// crowdb-chunkdb HTTP management API.
    ChunkdbHttp,
    /// crowdb-chunkdb crowdb-rpc listener.
    ChunkdbRpc,
    /// crowdb-diskio crowdb-rpc listener.
    DiskioRpc,
    /// crowdb-web HTTP service.
    Web,
    /// crowdb-chunk-kv-server HTTP management API.
    ChunkKvHttp,
    /// crowdb-chunk-kv-server crowdb-rpc listener.
    ChunkKvRpc,
    /// crowdb-access-server S3 HTTP service.
    AccessServerHttp,
    /// crowdb-access-server Iceberg HTTP service.
    AccessServerIcebergHttp,
    /// crowdb-access-server Dataset HTTP service.
    AccessServerDatasetHttp,
    /// Internal Access liveness/readiness HTTP service.
    AccessServerHealthHttp,
    /// Node monitor discovery and management HTTP.
    MonitorHttp,
}

impl ServicePort {
    /// Stable manifest key for this listener kind.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::PaxosKvServerMgmt => "kv_server_mgmt",
            Self::PaxosKvServerRpc => "kv_server_rpc",
            Self::DiskdbHttp => "diskdb_http",
            Self::DiskdbRpc => "diskdb_rpc",
            Self::ChunkdbHttp => "chunkdb_http",
            Self::ChunkdbRpc => "chunkdb_rpc",
            Self::DiskioRpc => "diskio_rpc",
            Self::Web => "web",
            Self::ChunkKvHttp => "chunk_kv_http",
            Self::ChunkKvRpc => "chunk_kv_rpc",
            Self::AccessServerHttp => "access_server_http",
            Self::AccessServerIcebergHttp => "access_server_iceberg_http",
            Self::AccessServerDatasetHttp => "access_server_dataset_http",
            Self::AccessServerHealthHttp => "access_server_health_http",
            Self::MonitorHttp => "monitor_http",
        }
    }

    /// Base (start) port for this service type.
    #[must_use]
    pub const fn base(self) -> u16 {
        match self {
            Self::PaxosKvServerMgmt => PAXOS_KV_SERVER_MGMT_BASE,
            Self::PaxosKvServerRpc => PAXOS_KV_SERVER_RPC_BASE,
            Self::DiskdbHttp => DISKDB_HTTP_BASE,
            Self::DiskdbRpc => DISKDB_RPC_BASE,
            Self::ChunkdbHttp => CHUNKDB_HTTP_BASE,
            Self::ChunkdbRpc => CHUNKDB_RPC_BASE,
            Self::DiskioRpc => DISKIO_RPC_BASE,
            Self::Web => WEB_BASE,
            Self::ChunkKvHttp => CHUNK_KV_HTTP_BASE,
            Self::ChunkKvRpc => CHUNK_KV_RPC_BASE,
            Self::AccessServerHttp => ACCESS_SERVER_HTTP_BASE,
            Self::AccessServerIcebergHttp => ACCESS_SERVER_ICEBERG_HTTP_BASE,
            Self::AccessServerDatasetHttp => ACCESS_SERVER_DATASET_HTTP_BASE,
            Self::AccessServerHealthHttp => ACCESS_SERVER_HEALTH_HTTP_BASE,
            Self::MonitorHttp => MONITOR_HTTP_BASE,
        }
    }

    /// Port stride between consecutive instances of the same service
    /// type on one node. All services use stride 1.
    #[must_use]
    pub const fn stride(self) -> u16 {
        let _ = self;
        1
    }

    /// Port for the `instance`-th instance of this service type on a
    /// node (0-based).
    #[must_use]
    pub const fn port(self, instance: u16) -> u16 {
        self.base() + instance * self.stride()
    }

    /// Number of instance ports reserved for each listener kind.
    #[must_use]
    pub const fn range_size(self) -> u16 {
        let _ = self;
        1000
    }
}
