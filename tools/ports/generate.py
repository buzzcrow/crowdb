"""Generate non-Rust defaults from protocol's ports.rs; --check never writes."""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "lib/crowdb-protocol/src/port/ports.rs"
TOKEN = re.compile(r"@([A-Z][A-Z_]+)(?:\+([0-9]+))?@")
NOTICE = "Generated by tools/ports/generate.py from ports.rs; edit the .in template."


def outputs():
    ports = {name: int(value) for name, value in re.findall(
        r"^pub const ([A-Z_]+): u16 = ([0-9]+);$", SOURCE.read_text(), re.MULTILINE)}
    if not ports:
        raise ValueError(f"no port definitions in {SOURCE}")
    copyright = "Copyright 2026-present Gian <crow.db@outlook.com>\nLicensed under the Apache License, Version 2.0."
    python = "\n".join("# " + line for line in copyright.splitlines())
    python += '\n\n"""Generated from ports.rs by tools/ports/generate.py; do not edit."""\n\n'
    python += "".join(f"{name} = {value}\n" for name, value in ports.items())
    yield ROOT / "container/oci-image/ports.py", python
    yield ROOT / "e2e-test/default_ports.py", python
    typescript = "\n".join("// " + line for line in copyright.splitlines())
    typescript += "\n\n// Generated from ports.rs by tools/ports/generate.py; do not edit.\n"
    typescript += "".join(f"export const {name} = {value};\n" for name, value in ports.items())
    yield ROOT / "app/crowdb-web/ui/src/ports.ts", typescript
    header = "\n".join("// " + line for line in copyright.splitlines())
    header += "\n\n// Generated from ports.rs by tools/ports/generate.py; do not edit.\n#pragma once\n\n#include <cstdint>\n\nnamespace crowdb::protocol\n{\n"
    header += "".join(f"inline constexpr std::uint16_t {name:<{max(map(len, ports))}} = {value};\n" for name, value in ports.items())
    header += "} // namespace crowdb::protocol\n"
    yield ROOT / "lib/crowdb-protocol/cpp/include/crowdb-protocol/ports.h", header
    templates = sorted((ROOT / "container").rglob("*.ports.in"))
    templates += sorted((ROOT / "app").glob("*/conf/*.ports.in"))
    for template in templates:
        def substitute(match):
            value = ports[match[1]] + int(match[2] or 0)
            if not 1 <= value <= 65535:
                raise ValueError(f"invalid port {match[0]} in {template}")
            return str(value)
        text = TOKEN.sub(substitute, template.read_text())
        lines = text.splitlines(keepends=True)
        index = 1 if lines and lines[0].startswith("#!") else 0
        lines.insert(index, "# " + NOTICE + "\n")
        yield template.with_name(template.name.removesuffix(".ports.in")), "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in outputs():
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        parser.exit(1, "Stale port defaults; run pixi run python tools/ports/generate.py:\n" + "\n".join(stale) + "\n")


if __name__ == "__main__":
    main()
